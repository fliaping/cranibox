#!/usr/bin/env bash
# Vendor the noVNC web application served for shared VNC desktops, and regenerate
# the list of files embedded in the node binary.
set -euo pipefail
version="${1:-1.7.0}"
root="$(cd "$(dirname "$0")/.." && pwd)"
target="$root/addons/novnc"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
curl -fsSL "https://github.com/novnc/noVNC/archive/refs/tags/v$version.tar.gz" -o "$work/novnc.tar.gz"
tar -xzf "$work/novnc.tar.gz" -C "$work"
source="$work/noVNC-$version"
rm -rf "$target"
mkdir -p "$target"
cp -R "$source/app" "$source/core" "$source/vendor" "$source/vnc.html" \
  "$source/LICENSE.txt" "$source/AUTHORS" "$target/"
find "$target" \( -name Makefile -o -name '*.md' -o -name README -o -name '*.po' -o -name '*.pot' \) -delete
echo "$version" > "$target/VERSION"

out="$root/crates/workspace-node/src/web/novnc_files.rs"
{
  echo "// Generated by scripts/vendor-novnc.sh from noVNC $version. Do not edit."
  echo "pub(super) const FILES: &[(&str, &[u8])] = &["
  (cd "$target" && find app core vendor vnc.html -type f | LC_ALL=C sort) | while read -r file; do
    echo "    (\"$file\", include_bytes!(\"../../../../addons/novnc/$file\")),"
  done
  echo "];"
} > "$out"
echo "Vendored noVNC $version into $target"
